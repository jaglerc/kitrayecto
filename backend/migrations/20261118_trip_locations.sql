ALTER TABLE trayectos
    ADD COLUMN IF NOT EXISTS origen_id integer REFERENCES ubicaciones(id);

CREATE TABLE IF NOT EXISTS paradas_trayecto (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trayecto_id integer NOT NULL REFERENCES trayectos(id) ON DELETE CASCADE,
    ubicacion_id integer NOT NULL REFERENCES ubicaciones(id),
    orden integer NOT NULL CHECK (orden > 0),
    UNIQUE (trayecto_id, orden)
);

CREATE TABLE IF NOT EXISTS movimientos_carga_trayecto (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parada_id integer NOT NULL REFERENCES paradas_trayecto(id) ON DELETE CASCADE,
    descripcion_producto varchar(150) NOT NULL,
    unidad_medida varchar(50) NOT NULL,
    tipo varchar(10) NOT NULL CHECK (tipo IN ('Recogida', 'Entrega')),
    cantidad numeric(10, 2) NOT NULL CHECK (cantidad > 0)
);

CREATE INDEX IF NOT EXISTS idx_paradas_trayecto ON paradas_trayecto (trayecto_id, orden);
